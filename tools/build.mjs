/**
 * Build `lib/client.js` from the numbered sources in `src/`.
 *
 * The Client module system loads a plain classic script that registers a lazy
 * factory through `window.__ModuleLoader__.load({ id, factory })`. The factory
 * runs at materialization and must return the plugin object
 * (`{ inject, apply }`). There is no build tool in this deployment that emits
 * that shape, so this script does the (trivial) wrapping itself:
 *
 *   src/00-*.js … src/90-*.js   →   lib/client.js
 *
 * Every source is ordinary ES5-compatible JavaScript with no imports, so the
 * concatenation needs no module resolution.
 *
 * Usage: node tools/build.mjs [--check]
 */
import fs from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..')
const SRC = path.join(ROOT, 'src')
const OUT = path.join(ROOT, 'lib', 'client.js')

const checkOnly = process.argv.includes('--check')

const files = fs
  .readdirSync(SRC)
  .filter((name) => /^\d+-[a-z0-9-]+\.js$/.test(name))
  .sort()

if (!files.length) {
  console.error('build: no sources found in src/')
  process.exit(1)
}

const banner = `/**
 * dsh-naiwa — 奶蛙桌宠 Client half (GENERATED — do not edit).
 *
 * Generated by tools/build.mjs from src/*.js. Edit the numbered sources there.
 * Sources:
${files.map((f) => ` *   src/${f}`).join('\n')}
 *
 * Rendering, animation, deformation, physics, audio and bubbles are a browser
 * port of the naiwa Python desktop pet; the accounting view is computed from
 * the ledger owned by dsh-whale-widget (read-only).
 */
`

const body = files
  .map((name) => {
    const text = fs.readFileSync(path.join(SRC, name), 'utf8')
    return `// ---- src/${name} ${'-'.repeat(Math.max(0, 60 - name.length))}\n${text}`
  })
  .join('\n\n')

const output = `${banner}
window.__ModuleLoader__.load({
  id: 'dsh-naiwa',
  factory: function (require) {
${indent(body, 4)}
    return CLIENT_EXPORTS
  },
})
`

function indent(text, spaces) {
  const pad = ' '.repeat(spaces)
  return text
    .split('\n')
    .map((line) => (line.length ? pad + line : line))
    .join('\n')
}

if (checkOnly) {
  const current = fs.existsSync(OUT) ? fs.readFileSync(OUT, 'utf8') : ''
  if (current !== output) {
    console.error('build --check: lib/client.js is stale, run `node tools/build.mjs`')
    process.exit(1)
  }
  console.log('build --check: lib/client.js is up to date')
  process.exit(0)
}

fs.mkdirSync(path.dirname(OUT), { recursive: true })
fs.writeFileSync(OUT, output, 'utf8')
console.log(`build: wrote ${path.relative(ROOT, OUT)} (${output.length} bytes) from ${files.length} sources`)
