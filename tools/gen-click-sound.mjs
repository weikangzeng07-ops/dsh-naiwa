/**
 * Generates the dsh-naiwa click sound.
 *
 * The original naiwa project has NO click sound (its only audio is
 * `media/laugh.wav`, triggered by the 10-click laugh threshold). This script
 * synthesises a NEW, original placeholder click so that "replace only the click
 * sound" is actually implemented rather than claimed.
 *
 * The sound is a short, soft frog "blip": a fast pitch-dropping sine with a
 * slight second harmonic and a very short filtered noise transient. It is
 * deliberately quiet and short (< 130 ms) so rapid clicking never piles up.
 *
 * Output: assets/audio/click.wav — 48 kHz, 16-bit, mono.
 * This file is generated by the project itself; no third-party audio is used.
 *
 * Run: node tools/gen-click-sound.mjs
 */
import fs from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..')
const OUT = path.join(ROOT, 'assets', 'audio', 'click.wav')

const RATE = 48000
const DURATION = 0.125
const N = Math.round(RATE * DURATION)

/** Deterministic PRNG so the generated asset is reproducible. */
function mulberry32(seed) {
  let a = seed >>> 0
  return () => {
    a = (a + 0x6d2b79f5) >>> 0
    let t = a
    t = Math.imul(t ^ (t >>> 15), t | 1)
    t ^= t + Math.imul(t ^ (t >>> 7), t | 61)
    return ((t ^ (t >>> 14)) >>> 0) / 4294967296
  }
}

const rand = mulberry32(0x9e3779b9)
const samples = new Float64Array(N)

// --- tone: a two-partial "boing" that drops from 720 Hz to 330 Hz -----------
const f0 = 720
const f1 = 330
const attack = 0.004
const decay = 0.055
let phase = 0
let phase2 = 0
for (let i = 0; i < N; i += 1) {
  const t = i / RATE
  const u = Math.min(1, t / DURATION)
  const freq = f0 * Math.pow(f1 / f0, Math.pow(u, 0.55))
  phase += (2 * Math.PI * freq) / RATE
  phase2 += (2 * Math.PI * freq * 2.02) / RATE
  const env = (1 - Math.exp(-t / attack)) * Math.exp(-t / decay)
  samples[i] = env * (Math.sin(phase) * 0.72 + Math.sin(phase2) * 0.14)
}

// --- transient: 6 ms of low-passed noise for a soft "tick" ------------------
let lp = 0
const noiseLen = Math.round(RATE * 0.006)
for (let i = 0; i < noiseLen; i += 1) {
  const t = i / RATE
  lp = lp * 0.72 + (rand() * 2 - 1) * 0.28
  samples[i] += lp * 0.30 * Math.exp(-t / 0.0016)
}

// --- gentle low-pass (one-pole, ~9 kHz) to remove digital harshness --------
let y = 0
const a = 0.72
for (let i = 0; i < N; i += 1) {
  y = y * a + samples[i] * (1 - a)
  samples[i] = y
}

// --- normalise to -6 dBFS and apply a 2 ms fade-out tail -------------------
let peak = 0
for (let i = 0; i < N; i += 1) peak = Math.max(peak, Math.abs(samples[i]))
const gain = peak > 0 ? 0.5 / peak : 1
const fadeOut = Math.round(RATE * 0.002)
for (let i = 0; i < N; i += 1) {
  let s = samples[i] * gain
  if (i >= N - fadeOut) s *= (N - i) / fadeOut
  samples[i] = Math.max(-1, Math.min(1, s))
}

// --- write a 16-bit mono WAV ----------------------------------------------
const dataBytes = N * 2
const buffer = Buffer.alloc(44 + dataBytes)
buffer.write('RIFF', 0, 'ascii')
buffer.writeUInt32LE(36 + dataBytes, 4)
buffer.write('WAVE', 8, 'ascii')
buffer.write('fmt ', 12, 'ascii')
buffer.writeUInt32LE(16, 16) // fmt chunk size
buffer.writeUInt16LE(1, 20) // PCM
buffer.writeUInt16LE(1, 22) // mono
buffer.writeUInt32LE(RATE, 24)
buffer.writeUInt32LE(RATE * 2, 28) // byte rate
buffer.writeUInt16LE(2, 32) // block align
buffer.writeUInt16LE(16, 34) // bits
buffer.write('data', 36, 'ascii')
buffer.writeUInt32LE(dataBytes, 40)
for (let i = 0; i < N; i += 1) {
  buffer.writeInt16LE(Math.round(samples[i] * 32767), 44 + i * 2)
}

fs.mkdirSync(path.dirname(OUT), { recursive: true })
fs.writeFileSync(OUT, buffer)
console.log(`wrote ${OUT} (${buffer.length} bytes, ${DURATION * 1000} ms, ${RATE} Hz mono)`)
